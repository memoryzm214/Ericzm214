# ---------- 应用 ----------
ps = lib.paras(d)
edits.sort(key=lambda x: -x[0])          # 从后往前，避免偏移
applied, failed = 0, []
for idx, (kind, old, new) in edits:
    p = ps[idx]
    if kind == 'sub':
        if old not in p['text']:
            failed.append((idx, old[:40])); continue
        newtext = p['text'].replace(old, new)
    else:
        newtext = new
    newxml = rebuild(p['xml'], newtext)
    d = d[:p['s']] + newxml + d[p['e']:]
    ps = lib.paras(d)                     # 重新解析，保持索引有效
    applied += 1

