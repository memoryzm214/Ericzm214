def esc(t):
    return t.replace('&','&amp;').replace('<','&lt;').replace('>','&gt;')

R_RE = re.compile(r'<w:r(?: [^>]*)?>.*?</w:r>', re.S)

def rebuild(pxml, new_text):
    """Replace all text of a paragraph with new_text, keeping pPr and first run's rPr."""
    runs = R_RE.findall(pxml)
    if not runs:
        raise RuntimeError('no runs')
    first = runs[0]
    rpr = re.search(r'<w:rPr>.*?</w:rPr>', first, re.S)
    rpr = rpr.group(0) if rpr else ''
    newrun = f'<w:r>{rpr}<w:t xml:space="preserve">{esc(new_text)}</w:t></w:r>'
    # remove every run, then append the new one before </w:p>
    out = R_RE.sub('', pxml)
    out = out.replace('</w:p>', newrun + '</w:p>')
    return out

