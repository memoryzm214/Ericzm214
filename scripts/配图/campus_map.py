    o.append(f'<path d="{BANK_P}" fill="{BANK}"/>')
    o.append(f'<path d="{RIVER_P}" fill="url(#wg)"/>')
    o.append(f'<path d="{RIVER_P}" fill="none" stroke="#FFFFFF" stroke-width="1.6" opacity=".5"/>')
    o.append('</g>')

    # 运动场地
    for kind, x, y, w, h, cn, en in FIELDS:
        if kind == 'track':
            r = S(min(w, h)) / 2
            o.append(rect(X(x), Y(y), S(w), S(h), '#C4DCB6', r))
            o.append(rect(X(x) + 9, Y(y) + 9, S(w) - 18, S(h) - 18, '#CFC0A4', r - 9))
            o.append(rect(X(x) + 30, Y(y) + 26, S(w) - 60, S(h) - 52, '#B4CFA6', 10))
            o.append(T(X(x + w / 2), Y(y + h / 2) - 2, cn, 17, 600, '#4F6247', 'middle'))
            o.append(T(X(x + w / 2), Y(y + h / 2) + 17, en, 9.5, 400, '#7B8C72', 'middle'))
        else:
            o.append(rect(X(x), Y(y), S(w), S(h), B3, 4))
            o.append(rect(X(x) + 3.5, Y(y) + 3.5, S(w) - 7, S(h) - 7, 'none', 3, .8, '#FFFFFF', 1.2))
            if S(w) >= S(h):
                o.append(T(X(x + w / 2), Y(y + h / 2) + 4.5, cn, 11.5, 500, B3T, 'middle'))
            else:
                for i, ch in enumerate(cn):
                    o.append(T(X(x + w / 2), Y(y) + 18 + i * 13, ch, 11.5, 500, B3T, 'middle'))

    # 道路
    for x, y, w, h in ROADS:
        o.append(rect(X(x) - 2, Y(y) - 2, S(w) + 4, S(h) + 4, ROAD_E, 2))
        o.append(rect(X(x), Y(y), S(w), S(h), ROAD, 2))
    o.append(f'<g transform="translate({OX},{OY}) scale({K})">')
    for pth, wid in ((YANHE, 30), (NANLI, 34)):
        o.append(f'<path d="{pth}" fill="none" stroke="{ROAD_E}" stroke-width="{wid+4}" stroke-linecap="butt"/>')
        o.append(f'<path d="{pth}" fill="none" stroke="{ROAD}" stroke-width="{wid}" stroke-linecap="butt"/>')
    o.append('</g>')
    # 中央大道中心线
    o.append(line(X(20), Y(693), X(1980), Y(693), '#D6E5CC', 1.6, dash='14 12'))

    # 建筑
    def draw_b(item):
        tier = item[5] if item[0] == 'r' else item[2]
        c, cd = {1: (B1, B1D), 2: (B2, B2D), 3: (B3, B3D)}[tier]
        g = []
        if item[0] == 'r':
            _, x, y, w, h = item[:5]
            g.append(rect(X(x) + 2.5, Y(y) + 3.5, S(w), S(h), '#3A5742', 3, .08))
            g.append(rect(X(x), Y(y), S(w), S(h), cd, 3))
            g.append(rect(X(x), Y(y), S(w), S(h) - 3.5, c, 3))
            if tier == 2:
                g.append(rect(X(x), Y(y), S(w), S(h), 'none', 3, .55, '#A8C29B', .9))
        else:
            pts = P(item[1])
            g.append(poly([(a + 2.5, b + 3.5) for a, b in pts], '#3A5742', .08))
            g.append(poly(pts, cd))
            g.append(poly([(a, b - 3.5) for a, b in pts], c))
            if tier == 2:
                g.append(poly(pts, 'none', .55, '#A8C29B', .9))
        return ''.join(g)

    for it in BUILDINGS:
        if it[0] == 'l':
            continue
        o.append(draw_b(it))

    # 建筑标注
    def label(item):
        if item[0] == 'l':
            _, lx, ly, tier, cn, en = item
            col = {1: B1T, 2: B2T, 3: B3T}[tier]
            return T(X(lx), Y(ly), cn, 13.5, 600, col, 'middle')
        tier = item[5] if item[0] == 'r' else item[2]
        col = {1: B1T, 2: B2T, 3: B3T}[tier]
        if item[0] == 'r':
            _, x, y, w, h, _, cn, en = item
            cx, cy = X(x + w / 2), Y(y + h / 2)
            bw, bh = S(w), S(h)
        else:
            cn, en = item[3], item[4]
            xs = [p[0] for p in item[1]]; ys = [p[1] for p in item[1]]
            if len(item) >= 7:
                cx, cy = X(item[5]), Y(item[6])
            else:
                cx, cy = X((min(xs) + max(xs)) / 2), Y((min(ys) + max(ys)) / 2)
            bw, bh = S(max(xs) - min(xs)), S(max(ys) - min(ys))
        if not cn:
            return ''
        g, n = [], len(cn)
        base = 13.5 if tier == 1 else 11.5
        wt = 600 if tier == 1 else 500
        pad = 8 if tier == 1 else 3

        # 1) 单行放得下
        fs = base
        if n * fs <= bw - pad:
            en_fs = 0
            if en and bh >= fs * 2.8:
                en_fs = min(8.4, (bw * 0.90) / (len(en) * 0.62))
                if en_fs < 6.6:
                    en_fs = 0
            if en_fs:
                g.append(T(cx, cy - 1, cn, fs, wt, col, 'middle'))
                g.append(T(cx, cy + fs + 2, en, en_fs, 400, col, 'middle', op=.70))
            else:
                g.append(T(cx, cy + fs * .36, cn, fs, wt, col, 'middle'))
            return ''.join(g)

        # 2) 竖排放得下
        if n * base * 1.20 <= bh - pad and base <= bw - pad:
            fs = min(base, 12)
