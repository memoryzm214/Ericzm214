def build():
    d, o = [], []
    o.append(rect(0, 0, W, H, BG))
    o.append(rect(X(0) - 14, Y(0) - 14, S(2000) + 28, S(1500) + 28, '#FFFFFF', 12))
    o.append(rect(X(0) - 14, Y(0) - 14, S(2000) + 28, S(1500) + 28, 'none', 12, 1, '#DCE7D4', 1.3))
    o.append(rect(X(0), Y(0), S(2000), S(1500), LAND, 8))

    for kind, g, c in GREENS:
        x, y, w, h = g
        o.append(rect(X(x), Y(y), S(w), S(h), c, 5))

    # 滨河带与水面
    d.append(f'<linearGradient id="wg" x1="0" y1="0" x2="0" y2="1">'
             f'<stop offset="0" stop-color="{WATER_D}"/><stop offset="1" stop-color="{WATER}"/></linearGradient>')
